"""Draw the system from the code: Python modules and their imports, the web app's
modules and their imports, the API endpoints, the tables, and the screens.

    uv run python -m lifekit.library.architecture > docs/content/architecture.md
"""

import ast
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def python_modules() -> dict[str, set[str]]:
    edges: dict[str, set[str]] = {}
    for path in sorted((ROOT / "lifekit").rglob("*.py")):
        name = ".".join(path.relative_to(ROOT).with_suffix("").parts)
        tree = ast.parse(path.read_text())
        edges[name] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module:
                module = node.module
                if node.level:
                    base = name.rsplit(".", node.level)[0]
                    module = f"{base}.{module}"
                if module.startswith("lifekit"):
                    edges[name].add(module)
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name.startswith("lifekit"):
                        edges[name].add(alias.name)
    return edges


def ts_modules() -> dict[str, set[str]]:
    edges: dict[str, set[str]] = {}
    src = ROOT / "web" / "src"
    for path in sorted(src.rglob("*")):
        if path.suffix not in (".ts", ".svelte") or "node_modules" in path.parts:
            continue
        name = str(path.relative_to(src))
        edges[name] = set()
        for match in re.finditer(r"from\s+'(\.[^']+)'", path.read_text()):
            target = (path.parent / match.group(1)).resolve()
            for candidate in (target, target.with_suffix(".ts"), target.with_suffix(".svelte")):
                if candidate.exists() and candidate.is_file():
                    edges[name].add(str(candidate.relative_to(src)))
                    break
    return edges


def endpoints() -> list[str]:
    text = (ROOT / "lifekit" / "api.py").read_text()
    return [f"{m.group(1).upper()} {m.group(2)}" for m in re.finditer(r'@app\.(get|post)\("([^"]+)"\)', text)]


def tables() -> list[str]:
    db = sqlite3.connect(ROOT / "packs" / "library.sqlite")
    return [r[0] for r in db.execute("SELECT name FROM sqlite_master WHERE type IN ('table') AND name NOT LIKE 'sqlite_%' AND name NOT LIKE 'passage_fts_%' ORDER BY name")]


def mermaid_id(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "_", name)


def main() -> None:
    py = python_modules()
    ts = ts_modules()
    out = ["# Architecture, drawn from the code", "",
           "Generated by `lifekit/library/architecture.py` from the imports in `lifekit/` and `web/src/`,",
           "the routes in `lifekit/api.py`, and the tables in `packs/library.sqlite`. Regenerate after any",
           "structural change; do not edit by hand.", ""]
    out += ["## Python: the pipeline, the API, and the fetch pass", "", "```mermaid", "graph LR"]
    for module, imports in py.items():
        if module.endswith("__init__"):
            continue
        short = module.replace("lifekit.", "")
        out.append(f'  {mermaid_id(module)}["{short}"]')
        for target in sorted(imports):
            if target.endswith("__init__") or target not in py:
                continue
            out.append(f"  {mermaid_id(module)} --> {mermaid_id(target)}")
    out += ["```", ""]
    out += ["## Web app: screens over the shared core", "", "```mermaid", "graph LR"]
    for module, imports in ts.items():
        out.append(f'  {mermaid_id(module)}["{module}"]')
        for target in sorted(imports):
            out.append(f"  {mermaid_id(module)} --> {mermaid_id(target)}")
    out += ["```", ""]
    out += ["## API routes (lifekit/api.py)", ""] + [f"- `{e}`" for e in endpoints()] + [""]
    out += ["## Tables (packs/library.sqlite)", ""] + [f"- `{t}`" for t in tables()] + [""]
    out += ["## Files on disk", "", "```",
            "packs/", "  library.sqlite            every table above",
            "  shelves/<shelf>/volumes.tsv   curated list; learned.tsv   what the fetch pass pulled",
            "  volumes/<id>/source.*, source.meta.json, cover.md, tags.json",
            "web/public/library.sqlite    the copy the browser loads; thumbs/, fonts/",
            "docs/progress/               screenshots and the thumbnails' first render", "```", ""]
    print("\n".join(out))


if __name__ == "__main__":
    main()
