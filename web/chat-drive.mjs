// Drive the chat against a running instance: two turns, a follow-up that needs history,
// the source link, the chats list, an offline send. Usage: BASE=... node chat-drive.mjs <outdir> <stamp>
import puppeteer from 'puppeteer-core';
const BASE = process.env.BASE ?? 'http://localhost:4173';
const [outDir, stamp] = process.argv.slice(2);
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage();
await page.setViewport({ width: 1440, height: 900 });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e).slice(0, 200)));
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const text = () => page.evaluate(() => document.body.innerText);
const until = async (fn, tries = 90, ms = 2000) => { for (let i = 0; i < tries; i++) { if (await fn()) return true; await wait(ms); } return false; };
const say = (n, ok, note = '') => console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${note ? '  (' + note + ')' : ''}`);
const shot = (n) => outDir && page.screenshot({ path: `${outDir}/${stamp}_chat-${n}.png` });
const type = async (q) => { await page.click('.input-row input'); await page.keyboard.type(q); await page.keyboard.press('Enter'); };
const bubbles = () => page.evaluate(() => [...document.querySelectorAll('.bubble.assistant')].map((b) => b.innerText));

await page.goto(`${BASE}/#/chat`, { waitUntil: 'networkidle0' }); await wait(800);
await page.evaluate(() => { localStorage.removeItem('lifekit.chats'); localStorage.removeItem('lifekit.forceOffline'); });
await page.goto(`${BASE}/?fresh#/chat`, { waitUntil: 'networkidle0' }); await wait(800);
say('chat screen has the input row', !!(await page.$('.input-row input')));
await type('how do I stop heavy bleeding from a leg wound');
say('pending bubble appears', await until(async () => (await page.$$('.bubble.assistant')).length === 1, 10, 300));
say('first answer arrives', await until(async () => !(await page.$('.dots')), 90, 2000));
const first = (await bubbles())[0] ?? '';
say('answer names a page and links it', /page \d+/i.test(first) && !!(await page.$('.bubble.assistant a.line')), first.slice(0, 80));
await shot('1-answer');
await type('and if that does not stop it?');
say('second answer arrives', await until(async () => (await page.$$('.bubble.assistant')).length === 2 && !(await page.$('.dots')), 90, 2000));
const second = (await bubbles())[1] ?? '';
say('follow-up is answered in context', /tourniquet|pressure|bleed/i.test(second), second.slice(0, 80));
say('thread url set', /#\/chat\/t/.test(await page.evaluate(() => location.hash)));
await shot('2-followup');
await type('how do I tune a piano');
say('off-topic answer arrives', await until(async () => (await page.$$('.bubble.assistant')).length === 3 && !(await page.$('.dots')), 90, 2000));
say('off-topic question is noted for the library', /Noted for the library/.test(await text()));
await shot('3-noted');
await page.goto(`${BASE}/#/chats`, { waitUntil: 'networkidle0' }); await wait(600);
say('chats list shows the thread with its count', /4 messages|6 messages/.test(await text()) && /stop heavy bleeding/.test(await text()));
await page.evaluate(() => document.querySelector('.chat-row').click()); await wait(800);
say('reopening restores the transcript', (await page.$$('.bubble.assistant')).length === 3);
await page.evaluate(() => document.querySelector('.rail .net, .rail button.net').click()); await wait(300);
await type('what do I do if I see a bear');
say('offline send stores the question', await until(async () => /stored/i.test((await bubbles()).at(-1) ?? ''), 10, 500));
await page.evaluate(() => document.querySelector('.rail .net, .rail button.net').click());
await shot('4-offline');
await page.setViewport({ width: 390, height: 1100, deviceScaleFactor: 2, isMobile: true, hasTouch: true }); await wait(1500);
await page.goto(`${BASE}/?phone#/chat`, { waitUntil: 'networkidle0' }); await wait(1200);
say('phone shows the chat with the nav', !!(await page.$('.input-row input')) && await page.evaluate(() => getComputedStyle(document.querySelector('.nav')).display !== 'none'));
say('phone: no horizontal scroll', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
await shot('5-phone');
say('no page errors', errors.length === 0, errors[0] ?? '');
await browser.close();
